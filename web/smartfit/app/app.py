import os
import json
import requests
from flask import Flask, request, jsonify, render_template, render_template_string

app = Flask(__name__)

# In-memory storage for user configuration and health logs
USER_DATA = {
    "profile": {
        "username": "alex_health_user",
        "weight_goal": "75kg",
        "daily_calories": 2200,
        "llm_endpoint": "https://api.openai.com/v1/chat/completions"
    },
    "logs": [
        {"day": "Monday", "calories": 2100, "water_l": 2.5},
        {"day": "Tuesday", "calories": 1950, "water_l": 3.0},
        {"day": "Wednesday", "calories": 2300, "water_l": 2.0}
    ]
}

# Base directory for custom report exports
REPORTS_DIR = os.path.join(os.path.dirname(__file__), "templates", "exports")
os.makedirs(REPORTS_DIR, exist_ok=True)

# --- Feature 1: User Profile Settings (Vulnerable to Unsanitized Endpoint Input) ---
@app.route('/api/profile', methods=['GET', 'POST'])
def profile():
    if request.method == 'POST':
        data = request.get_json() or {}
        
        # Updates settings without restricting endpoint destination or scheme
        if 'llm_endpoint' in data:
            USER_DATA["profile"]["llm_endpoint"] = str(data['llm_endpoint'])
        if 'weight_goal' in data:
            USER_DATA["profile"]["weight_goal"] = str(data['weight_goal'])
        if 'daily_calories' in data:
            USER_DATA["profile"]["daily_calories"] = int(data['daily_calories'])
            
        return jsonify({"status": "updated", "profile": USER_DATA["profile"]})
    
    return jsonify(USER_DATA["profile"])

# --- Feature 2: Meal & Activity Logging ---
@app.route('/api/logs', methods=['GET', 'POST'])
def logs():
    if request.method == 'POST':
        data = request.get_json() or {}
        if 'day' in data and 'calories' in data:
            USER_DATA["logs"].append({
                "day": str(data['day']),
                "calories": int(data['calories']),
                "water_l": float(data.get('water_l', 2.0))
            })
            return jsonify({"status": "logged", "logs": USER_DATA["logs"]})
        return jsonify({"error": "Invalid log entry"}), 400
    
    return jsonify(USER_DATA["logs"])

# --- Feature 3: Secondary Tool Routine (Custom Report Exporter) ---
def resolve_report_path(filename, must_exist=False):
    """
    Confines a report name to REPORTS_DIR.
    Blocks absolute paths and ../ traversal outside the exports sandbox.
    """
    if not filename or "\x00" in str(filename):
        return None

    base = os.path.realpath(REPORTS_DIR)
    target = os.path.realpath(os.path.normpath(os.path.join(base, str(filename))))

    if not target.startswith(base + os.sep):
        return None
    if os.path.isdir(target):
        return None
    if must_exist and not os.path.isfile(target):
        return None
    return target


def tool_save_report_template(filename, content):
    """
    Saves custom summary reports generated by the assistant.
    Writes are restricted to REPORTS_DIR.
    """
    try:
        target_path = resolve_report_path(filename, must_exist=False)
        if target_path is None:
            return "File write error: invalid report filename"

        # Ensure parent directories exist
        os.makedirs(os.path.dirname(target_path), exist_ok=True)

        with open(target_path, "w", encoding="utf-8") as f:
            f.write(content)

        return f"Report successfully written to {filename}"
    except Exception as e:
        return f"File write error: {str(e)}"

# --- Feature 4: AI Chat Integration with Tool Dispatcher ---
@app.route('/api/chat', methods=['POST'])
def chat():
    user_message = request.json.get("message", "")
    
    headers = {
        "Authorization": "Bearer smartfit-internal-service-token",
        "Content-Type": "application/json"
    }
    
    payload = {
        "model": "gpt-4-health",
        "messages": [
            {"role": "system", "content": "You are SmartFit AI. Help users track fitness and generate reports."},
            {"role": "user", "content": user_message}
        ]
    }
    
    target_url = USER_DATA["profile"]["llm_endpoint"]
    
    try:
        # Outbound request to user-configured endpoint
        response = requests.post(target_url, headers=headers, json=payload, timeout=5)
        res_data = response.json()
    except Exception as e:
        return jsonify({"error": f"Model connection failure: {str(e)}"}), 502

    # Parse potential tool calls from the returned response
    try:
        choices = res_data.get("choices", [])
        if not choices:
            return jsonify({"response": "No choice returned from model."})
            
        message_obj = choices[0].get("message", {})
        
        # Process tool calls
        if "tool_calls" in message_obj:
            tool_outputs = []
            for tool in message_obj["tool_calls"]:
                func_name = tool.get("function", {}).get("name")
                args_str = tool.get("function", {}).get("arguments", "{}")
                args = json.loads(args_str)
                
                if func_name == "export_report":
                    out = tool_save_report_template(
                        args.get("filename", "default.html"),
                        args.get("content", "")
                    )
                    tool_outputs.append(out)
                    
            return jsonify({"assistant": "Tool execution completed.", "results": tool_outputs})
            
        return jsonify({"assistant": message_obj.get("content", "")})
    except Exception as e:
        return jsonify({"error": f"Response parsing error: {str(e)}"}), 500

# --- Feature 5: Render Saved Reports ---
@app.route('/view_report/<path:report_name>')
def view_report(report_name):
    """
    Renders custom generated reports.
    Reports are resolved strictly inside REPORTS_DIR (no traversal).
    """
    target_path = resolve_report_path(report_name, must_exist=True)
    if target_path is None:
        return "Report not found", 404

    with open(target_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Render template dynamically
    return render_template_string(content)

@app.route('/')
def index():
    return render_template('index.html', profile=USER_DATA["profile"], logs=USER_DATA["logs"])

if __name__ == '__main__':
    app.run(host='0.0.0.0', port=5000)
